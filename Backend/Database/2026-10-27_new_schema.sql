-- TecnoFix: migración de Neon al modelo de 4 tablas (nombres en inglés). FASE 1 de 3.
--
--   Fase 1  2026-10-27_new_schema.sql      Crea users, equipment_types, repair_orders y
--                                          order_logs y copia los usuarios. NO borra nada:
--                                          el backend anterior sigue usando "User", "Client", etc.
--   Fase 2  2026-10-27_sync_users.sql      Copia los usuarios creados en las tablas antiguas
--                                          después de la fase 1 (se puede repetir sin riesgo).
--   Fase 3  2026-10-27_drop_old_tables.sql Elimina las tablas antiguas. Solo cuando el backend
--                                          nuevo esté desplegado y verificado. NO tiene vuelta atrás.
--
-- Orden de despliegue: fase 1 -> desplegar backend y frontend nuevos -> fase 2 -> verificar -> fase 3.
--
-- Requisitos: los enums user_role (ADMIN, TECHNICIAN, CLIENT) y order_status
-- (RECEIVED, IN_DIAGNOSIS, QUOTED, IN_REPAIR, READY_FOR_PICKUP, DELIVERED, REJECTED)
-- ya existen y se reutilizan sin cambios.
--
-- Se ejecuta en UNA transacción: si falla una verificación, no se aplica nada.

BEGIN;

CREATE TABLE users (
  id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  role           user_role   NOT NULL,
  full_name      varchar     NOT NULL,
  email          varchar     NOT NULL UNIQUE,
  password       varchar     NOT NULL,            -- hash BCrypt
  rut            varchar(9)  UNIQUE,              -- solo clientes
  phone          varchar,                         -- solo clientes
  specialty      varchar,                         -- solo técnicos
  account_status boolean     NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE equipment_types (
  id          uuid    PRIMARY KEY DEFAULT gen_random_uuid(),
  name        varchar NOT NULL UNIQUE,
  description text,
  enabled     boolean NOT NULL DEFAULT true
);

CREATE TABLE repair_orders (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id           uuid NOT NULL REFERENCES users(id),
  technician_id       uuid REFERENCES users(id),
  equipment_type_id   uuid NOT NULL REFERENCES equipment_types(id),
  status              order_status NOT NULL DEFAULT 'RECEIVED',
  brand_model         varchar NOT NULL,
  serial_number       varchar,
  fault_description   text NOT NULL,
  accessories         text,
  technical_diagnosis text,
  labor_cost          numeric(12,2) NOT NULL DEFAULT 0,
  parts_cost          numeric(12,2) NOT NULL DEFAULT 0,
  total_cost          numeric(12,2) GENERATED ALWAYS AS (labor_cost + parts_cost) STORED,
  budget_approved     boolean,
  decision_date       timestamptz,
  pickup_name         varchar,
  delivery_notes      text,
  received_at         timestamptz NOT NULL DEFAULT now(),
  delivered_at        timestamptz
);

CREATE TABLE order_logs (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id            integer NOT NULL REFERENCES repair_orders(id),
  responsible_user_id uuid    NOT NULL REFERENCES users(id),
  logged_status       order_status NOT NULL,
  comment             text,
  logged_at           timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_repair_orders_client_id         ON repair_orders (client_id);
CREATE INDEX idx_repair_orders_technician_id     ON repair_orders (technician_id);
CREATE INDEX idx_repair_orders_equipment_type_id ON repair_orders (equipment_type_id);
CREATE INDEX idx_repair_orders_status            ON repair_orders (status);
CREATE INDEX idx_order_logs_order_id             ON order_logs (order_id);
CREATE INDEX idx_order_logs_responsible_user_id  ON order_logs (responsible_user_id);

-- Verificación 1: no se pierden órdenes (las tablas de órdenes deben estar vacías).
DO $$
BEGIN
  IF (SELECT count(*) FROM "RepairOrder") + (SELECT count(*) FROM "Diagnosis")
     + (SELECT count(*) FROM "OrderLog") > 0 THEN
    RAISE EXCEPTION 'Las tablas antiguas de órdenes tienen datos; migración cancelada';
  END IF;
END $$;

-- Copia de usuarios: se conservan los hashes BCrypt, así las contraseñas siguen funcionando.
INSERT INTO users (role, full_name, email, password, rut, phone, specialty, account_status)
SELECT u.role, u.name, u.email, u.password, c.rut, c.phone, t.technician_type, COALESCE(t.enabled, true)
FROM "User" u
LEFT JOIN "Client" c     ON c.user_id = u.user_id
LEFT JOIN "Technician" t ON t.user_id = u.user_id
ORDER BY u.user_id;

-- Verificación 2: se copiaron todos los usuarios.
DO $$
BEGIN
  IF (SELECT count(*) FROM users) <> (SELECT count(*) FROM "User") THEN
    RAISE EXCEPTION 'La cantidad de usuarios no coincide; migración cancelada';
  END IF;
END $$;


COMMIT;
